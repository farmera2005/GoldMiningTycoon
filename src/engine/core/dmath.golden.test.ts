describe('dmath golden values', () => {
  it('pins about 200 exact outputs', () => {
    expect(GOLDEN.length).toBeGreaterThanOrEqual(200);
    const fns = dmath as unknown as Record<Fn, (...args: number[]) => number>;
    const mismatches: string[] = [];
    for (const [fn, args, want] of GOLDEN) {
      const got = bits(fns[fn](...args));
      if (got !== want) mismatches.push(`${fn}(${args.join(', ')}) = ${got}, pinned ${want}`);
    }
    expect(mismatches).toEqual([]);
  });
});
